#!/usr/bin/env python3
"""Generate design/brand/prism-icon.svg (the 1024px dock/app icon) from the
mark geometry in src/components/ui/PrismLogo.tsx, so the icon can never drift
from the in-app mark. Then rasterize + run `npx tauri icon` (see --help).

Usage: build-dock-icon.py [--ring PX] [--out PATH] [--png PATH]
  --ring  gradient border width out of 1024 (default 28, owner pick 2026-10-19)
  --out   SVG output path (default design/brand/prism-icon.svg)
  --png   also rasterize to this PNG via the project's Playwright Chromium
"""
import argparse, json, pathlib, re, subprocess, sys
ROOT = pathlib.Path(__file__).resolve().parents[2]
ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
ap.add_argument("--ring", type=int, default=28)
ap.add_argument("--out", default=str(ROOT / "design/brand/prism-icon.svg"))
ap.add_argument("--png", default=None)
a = ap.parse_args()

src = (ROOT / "src/components/ui/PrismLogo.tsx").read_text()
def const(name):
    m = re.search(rf"export const {name} = (.+?);\n", src, re.S)
    if not m: sys.exit(f"constant {name} not found in PrismLogo.tsx")
    v = m.group(1).strip()
    if v.startswith("'"): return v.strip("'")
    if v.startswith("{"): return json.loads(re.sub(r"(\w+):", r'"\1":', v))
    return float(v)
TRI, AUD, VID, EXIT = (const(n) for n in ("PRISM_TRIANGLE", "PRISM_AUDIO_BEAM", "PRISM_VIDEO_BEAM", "PRISM_EXIT_BEAM"))
MEET, AE, VE = const("PRISM_MEET"), const("PRISM_AUDIO_ENTRY"), const("PRISM_VIDEO_ENTRY")
BW, EW, OW = const("PRISM_BEAM_WIDTH"), const("PRISM_EXIT_WIDTH"), const("PRISM_OUTLINE_WIDTH")
TEAL, ORANGE, PANEL = "#00D4C8", "#FF8C42", "#0A0E1A"

r = a.ring; R_OUT = 230; R_IN = R_OUT - r
# Mark: 120x64 viewBox, scaled to ~700px wide and centred optically
# (the exit beam drops right, so the group is nudged up slightly).
S = 6.0; TX = (1024 - 120 * S) / 2; TY = (1024 - 64 * S) / 2 - 20
merge = "".join(
    f'<linearGradient id="m{k}" gradientUnits="userSpaceOnUse" x1="{p["x"]}" y1="{p["y"]}" x2="{MEET["x"]}" y2="{MEET["y"]}">'
    f'<stop offset="0" stop-color="#fff" stop-opacity="0"/><stop offset="1" stop-color="#fff"/></linearGradient>'
    for k, p in (("a", AE), ("v", VE)))
svg = f'''<svg width="1024" height="1024" viewBox="0 0 1024 1024" xmlns="http://www.w3.org/2000/svg">
  <!-- GENERATED by design/brand/build-dock-icon.py from PrismLogo.tsx — do not hand-edit.
       Gradient edge ({r}px), dark panel, refraction prism mark. -->
  <defs>
    <linearGradient id="brand" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0%" stop-color="{ORANGE}"/><stop offset="100%" stop-color="{TEAL}"/>
    </linearGradient>
    {merge}
  </defs>
  <rect width="1024" height="1024" rx="{R_OUT}" fill="url(#brand)"/>
  <rect x="{r}" y="{r}" width="{1024 - 2 * r}" height="{1024 - 2 * r}" rx="{R_IN}" fill="{PANEL}"/>
  <g transform="translate({TX:.1f} {TY:.1f}) scale({S})" fill="none" stroke-linecap="round" stroke-linejoin="round">
    <polygon points="{TRI}" fill="rgba(255,255,255,0.04)" stroke="rgba(255,255,255,0.9)" stroke-width="{OW}"/>
    <path d="{AUD}" stroke="{TEAL}" stroke-width="{BW}"/>
    <path d="{VID}" stroke="{ORANGE}" stroke-width="{BW}"/>
    <line x1="{AE["x"]}" y1="{AE["y"]}" x2="{MEET["x"]}" y2="{MEET["y"]}" stroke="url(#ma)" stroke-width="{BW}"/>
    <line x1="{VE["x"]}" y1="{VE["y"]}" x2="{MEET["x"]}" y2="{MEET["y"]}" stroke="url(#mv)" stroke-width="{BW}"/>
    <path d="{EXIT}" stroke="#fff" stroke-width="{EW}"/>
  </g>
</svg>
'''
pathlib.Path(a.out).write_text(svg)
print("wrote", a.out)
if a.png:
    js = f"""const {{ chromium }} = require({json.dumps(str(ROOT / 'node_modules/playwright'))});
(async () => {{ const b = await chromium.launch(); const p = await b.newPage({{ viewport: {{ width: 1024, height: 1024 }} }});
await p.goto('file://' + {json.dumps(str(pathlib.Path(a.out).resolve()))});
await p.screenshot({{ path: {json.dumps(a.png)}, omitBackground: true }}); await b.close(); }})();"""
    subprocess.run(["node", "-e", js], check=True)
    print("wrote", a.png)
