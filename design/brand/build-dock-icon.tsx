/**
 * Generate design/brand/prism-icon.svg (1024px dock/app icon) by rendering
 * the REAL <PrismMark> component to static SVG, so the dock icon is the same
 * drawing as the in-app logo, never a hand-copied approximation.
 *
 * Icon body follows the native macOS grid, MEASURED from the system's own app
 * icons (design/brand/measure-native-icon.py on /System/Applications/*.app,
 * macOS 26): an 824px body inset 100px on the 1024 canvas (80.5% fill — the
 * transparent margin is what makes it sit at native size in the Dock), with
 * superellipse ("squircle") corners: quadrant radius 286px, exponent 3.3.
 * That shape matches the native mask to within 0.16% of its pixels; a plain
 * rounded rect (r=194) misses by 0.43%.
 *
 * Usage: npx vite-node design/brand/build-dock-icon.tsx [--ring PX] [--png OUT.png]
 *   --ring  gradient edge width in canvas px (default 22: the owner's 28/1024
 *           pick, rescaled to the 824px body)
 *   --png   also rasterize to OUT.png (transparent margin) via Playwright
 */
import { renderToStaticMarkup } from 'react-dom/server';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { PrismMark } from '../../src/components/ui/PrismLogo';

const args = process.argv.slice(2);
if (args.includes('--help') || args.includes('-h')) {
  console.log('usage: npx vite-node design/brand/build-dock-icon.tsx [--ring PX] [--png OUT.png]');
  process.exit(0);
}
const known = new Set(['--ring', '--png']);
for (let i = 0; i < args.length; i += 2) {
  if (!known.has(args[i])) {
    console.error(`unknown argument ${args[i]}\nusage: npx vite-node design/brand/build-dock-icon.tsx [--ring PX] [--png OUT.png]`);
    process.exit(2);
  }
}
const opt = (k: string) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : undefined; };
const ring = Number(opt('--ring') ?? 22);
const png = opt('--png');

const TEAL = '#00D4C8';
const ORANGE = '#FF8C42';
const PANEL = '#0A0E1A';
const OFF = 100;
const BODY = 824;

/** Superellipse-cornered square: quadrant radius R, exponent n. */
function squircle(off: number, size: number, R: number, n: number, steps = 24): string {
  const x0 = off, y0 = off, x1 = off + size, y1 = off + size;
  const quad = (cx: number, cy: number, sx: number, sy: number) =>
    Array.from({ length: steps + 1 }, (_, i) => {
      const t = (Math.PI / 2) * (i / steps);
      return [cx + sx * R * Math.cos(t) ** (2 / n), cy + sy * R * Math.sin(t) ** (2 / n)];
    });
  const pts = [
    ...quad(x1 - R, y0 + R, 1, -1).reverse(),
    ...quad(x1 - R, y1 - R, 1, 1),
    ...quad(x0 + R, y1 - R, -1, 1).reverse(),
    ...quad(x0 + R, y0 + R, -1, -1),
  ];
  return 'M ' + pts.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join(' L ') + ' Z';
}

// Inner panel: same superellipse, inset by the ring, radius shrunk with it.
const R = 286 * (BODY / 824);
const outer = squircle(OFF, BODY, R, 3.3);
const inner = squircle(OFF + ring, BODY - 2 * ring, R - ring, 3.3);

// Mark: the 120x64 drawing at 120% of the body width, centred on it. The
// prism then fills ~43% of the body (owner: "take up more of the frame");
// the beams run on past the box (reach) and are clipped by the panel, so
// the streams cross the whole icon edge to edge. The prism apex sits at the
// box's x centre (geometry --cx 60), so centring the box centres the prism.
const markW = BODY * 1.2;
const markH = (markW * 64) / 120;
// The icon is DISPLAYED far smaller than 1024px (Dock ~64pt, Finder up to
// ~128pt), so the fringes are sized for the mark at ~128pt, not at 1024:
// sized for 1024 they would vanish in the Dock.
const ICON_MARK_PX = 128;
const unitsPerPx = 120 / markW;
const reach = Math.max(0, Math.ceil(((BODY - 2 * ring - markW) / 2) * unitsPerPx)) + 4;
// Rendered inside an <svg> so React treats the elements as SVG (no casing
// warnings); the wrapper is stripped again below.
const mark = renderToStaticMarkup(<svg><PrismMark reach={reach} pxWidth={ICON_MARK_PX} /></svg>)
  .replace(/^<svg>/, '')
  .replace(/<\/svg>$/, '')
  .replaceAll('var(--color-stream-audio)', TEAL)
  .replaceAll('var(--color-stream-video)', ORANGE);

const svg = `<svg width="1024" height="1024" viewBox="0 0 1024 1024" xmlns="http://www.w3.org/2000/svg">
  <!-- GENERATED by design/brand/build-dock-icon.tsx from <PrismMark> — do not hand-edit.
       Native macOS icon grid (824px squircle body, 100px margin), ${ring}px gradient edge. -->
  <defs>
    <linearGradient id="brand" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0%" stop-color="${ORANGE}"/><stop offset="100%" stop-color="${TEAL}"/>
    </linearGradient>
    <clipPath id="panel"><path d="${inner}"/></clipPath>
  </defs>
  <path d="${outer}" fill="url(#brand)"/>
  <path d="${inner}" fill="${PANEL}"/>
  <g clip-path="url(#panel)">
    <svg x="${(1024 - markW) / 2}" y="${(1024 - markH) / 2}" width="${markW}" height="${markH}" viewBox="0 0 120 64" overflow="visible">
      ${mark}
    </svg>
  </g>
</svg>
`;
const out = resolve(__dirname, 'prism-icon.svg');
writeFileSync(out, svg);
console.log('wrote', out);

if (png) {
  const { chromium } = await import('playwright');
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1024, height: 1024 } });
  await page.goto('file://' + out);
  await page.screenshot({ path: png, omitBackground: true });
  await browser.close();
  console.log('wrote', png);
}
