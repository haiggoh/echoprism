/**
 * Generate design/brand/prism-icon.svg (1024px dock/app icon) by rendering
 * <PrismAppIcon margin> — the SAME component the app's sidebar shows — to
 * static SVG, with the theme colours substituted. Icon and in-app icon are
 * one component, so they stay in sync by construction. Layout rationale
 * (native macOS grid, measured squircle) lives in PrismAppIcon.tsx.
 *
 * Usage: npx vite-node design/brand/build-dock-icon.tsx [--png OUT.png]
 *   --png   also rasterize to OUT.png (transparent margin) via Playwright,
 *           ready for `npx tauri icon OUT.png`
 */
import { renderToStaticMarkup } from 'react-dom/server';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { PrismAppIcon } from '../../src/components/ui/PrismAppIcon';

const args = process.argv.slice(2);
if (args.includes('--help') || args.includes('-h')) {
  console.log('usage: npx vite-node design/brand/build-dock-icon.tsx [--png OUT.png]');
  process.exit(0);
}
const known = new Set(['--png']);
for (let i = 0; i < args.length; i += 2) {
  if (!known.has(args[i])) {
    console.error(`unknown argument ${args[i]}\nusage: npx vite-node design/brand/build-dock-icon.tsx [--png OUT.png]`);
    process.exit(2);
  }
}
const opt = (k: string) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : undefined; };
const png = opt('--png');

const COLORS: Record<string, string> = {
  'var(--color-stream-audio)': '#00D4C8',
  'var(--color-stream-video)': '#FF8C42',
  'var(--color-bg)': '#0A0E1A',
};

// The icon is DISPLAYED far smaller than 1024px (Dock ~64pt, Finder up to
// ~128pt), so the fringes are tuned for the body at ~128pt, not at 1024:
// tuned for 1024 they would vanish in the Dock.
let markup = renderToStaticMarkup(<PrismAppIcon size={1024} margin displayPx={128} />);
for (const [v, hex] of Object.entries(COLORS)) markup = markup.replaceAll(v, hex);
if (markup.includes('var(--')) {
  console.error('unresolved CSS variable left in the icon:', markup.match(/var\(--[^)]*\)/)?.[0]);
  process.exit(1);
}
const svg = markup.replace(
  '<svg ',
  '<svg xmlns="http://www.w3.org/2000/svg" ',
).replace(
  /^(<svg[^>]*>)/,
  '$1\n  <!-- GENERATED by design/brand/build-dock-icon.tsx from <PrismAppIcon> — do not hand-edit. -->',
);
const out = resolve(__dirname, 'prism-icon.svg');
writeFileSync(out, svg);
console.log('wrote', out);

if (png) {
  const { chromium } = await import('playwright');
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1024, height: 1024 } });
  await page.goto('file://' + out);
  await page.screenshot({ path: png, omitBackground: true });
  await browser.close();
  console.log('wrote', png);
}
