// @vitest-environment jsdom
/**
 * PrismLogo — the brand mark (2026-10-18 owner redesign).
 *
 * Discriminants:
 *  - "pales the video stream in audio-only mode" fails if the audioOnly ->
 *    opacity-0.18 mapping on the video beam is removed (D-spec: "the orange
 *    stream turns a very pale desaturated orange, barely visible").
 *  - "straight beam segments" fails if the beam paths regress to curved
 *    commands (owner: "perfectly straight not curved").
 */
import { describe, it, expect, afterEach } from 'vitest';
import { cleanup, render } from '@testing-library/react';
import { PrismLogo, PRISM_GEOMETRY as G } from '../components/ui/PrismLogo';
import { PrismBadge } from '../components/ui/PrismBadge';

afterEach(cleanup);

const PALE = '0.18'; // faint trace (owner 2026-10-19: "even more subdued")

describe('PrismLogo', () => {
  it('renders as a decorative mark (hidden from assistive tech)', () => {
    const { container } = render(<PrismLogo />);
    const svg = container.querySelector('svg');
    expect(svg).not.toBeNull();
    expect(svg!.getAttribute('aria-hidden')).toBe('true');
  });

  it('shows both streams saturated by default', () => {
    const { getByTestId } = render(<PrismLogo />);
    expect(getByTestId('mark-audio-beam').getAttribute('opacity')).toBe('1');
    expect(getByTestId('mark-video-beam').getAttribute('opacity')).toBe('1');
  });

  it('pales the video stream in audio-only mode; audio stays saturated', () => {
    const { getByTestId } = render(<PrismLogo audioOnly />);
    const video = getByTestId('mark-video-beam');
    expect(video.getAttribute('opacity')).toBe(PALE);
    expect(video.style.filter).toContain('saturate'); // desaturated, not just dimmed
    expect(getByTestId('mark-audio-beam').getAttribute('opacity')).toBe('1');
  });

  it('uses straight beam segments (no curve commands)', () => {
    const { getByTestId } = render(<PrismLogo />);
    for (const id of ['mark-audio-beam', 'mark-video-beam']) {
      const d = getByTestId(id).getAttribute('d') ?? '';
      expect(d).toMatch(/^[ML\s0-9.-]+$/); // only M/L commands + coordinates
    }
  });

  // v4 geometry invariants (owner 2026-10-19 17:28). Each fails if the
  // geometry is hand-edited instead of regenerated by prism-geometry.py.
  const nums = (d: string) => d.replace(/[MLZ,]/g, ' ').trim().split(/\s+/).map(Number);
  const tri = nums(G.triangle);
  const first = (d: string) => nums(d).slice(0, 2);
  const last = (d: string) => nums(d).slice(-2);
  const yAtEdge = (d: string) => first(d)[1];

  it('the streams cross at the triangle centroid (centre of gravity)', () => {
    expect(G.meet.x).toBeCloseTo((tri[0] + tri[2] + tri[4]) / 3, 1);
    expect(G.meet.y).toBeCloseTo((tri[1] + tri[3] + tri[5]) / 3, 1);
    expect(last(G.video.beam)).toEqual([G.meet.x, G.meet.y]);
    expect(last(G.audio.beam)).toEqual([G.meet.x, G.meet.y]);
  });

  it('video enters from ABOVE audio (timeline order: video track over audio)', () => {
    expect(yAtEdge(G.video.beam)).toBeLessThan(yAtEdge(G.audio.beam));
  });

  it('the exit band leaves level or rising, never falling', () => {
    const risingDeg = (Math.atan2(-G.exitDir.y, G.exitDir.x) * 180) / Math.PI; // y is down
    expect(risingDeg).toBeGreaterThanOrEqual(0);
    expect(risingDeg).toBeLessThanOrEqual(10);
  });

  it('the band (and its fringes) starts AT the focus, not at the exit face', () => {
    const { getByTestId } = render(<PrismLogo size={120} />);
    expect(first(getByTestId('mark-exit-wedge').getAttribute('d') ?? '')).toEqual([G.meet.x, G.meet.y]);
  });

  it('fringes are inverted vs entry: teal on top, orange at the bottom', () => {
    const { container } = render(<PrismLogo size={120} />);
    const grad = [...container.querySelectorAll('linearGradient')].find((g) => g.id.endsWith('-band'))!;
    const colors = [...grad.querySelectorAll('stop')].map((s) => s.getAttribute('stop-color'));
    expect(colors[0]).toBe('var(--color-stream-audio)');
    expect(colors[colors.length - 1]).toBe('var(--color-stream-video)');
  });

  it('beams run past the viewBox edges (continue to infinity, clipped)', () => {
    const { getByTestId } = render(<PrismLogo size={120} />);
    expect(first(getByTestId('mark-video-beam').getAttribute('d') ?? '')[0]).toBeLessThan(0);
    expect(first(getByTestId('mark-audio-beam').getAttribute('d') ?? '')[0]).toBeLessThan(0);
    expect(Math.max(...nums(getByTestId('mark-exit-band').getAttribute('d') ?? '').filter((_, i) => i % 2 === 0))).toBeGreaterThan(120);
  });

  // Owner 2026-10-19: in the sidebar/header badges the beams must reach the
  // gradient frame (like the dock icon) — no gap at the beam ends. The badge
  // widens the SVG viewBox to the whole panel, and the beams must cross it.
  it('badge beams reach the panel edges', () => {
    const { container, getByTestId } = render(<PrismBadge width={64} aspect={2} />);
    const vb = (container.querySelector('svg')!.getAttribute('viewBox') ?? '').split(' ').map(Number);
    const [vx, , vw] = vb;
    expect(first(getByTestId('mark-video-beam').getAttribute('d') ?? '')[0]).toBeLessThanOrEqual(vx);
    const xs = nums(getByTestId('mark-exit-band').getAttribute('d') ?? '').filter((_, i) => i % 2 === 0);
    expect(Math.max(...xs)).toBeGreaterThanOrEqual(vx + vw);
  });
});
