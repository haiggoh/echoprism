import { useId } from 'react';

/**
 * PrismLogo — the EchoPrism brand mark (v3, owner spec 2026-10-19).
 *
 * A reverse prism traced with Snell's law (n = 1.5): the audio (teal) and
 * video (orange) streams arrive from the left, each bends toward the face
 * normal as it enters the glass, and they CROSS at the triangle's centroid
 * (its centre of gravity). From there one white beam carries on to the right
 * face and refracts out RISING slightly (+3 degrees): a falling line reads as
 * a downward trend. Because the streams crossed, their colour order is
 * inverted on the way out, shown as thin fringes on the thick white beam —
 * an imperfect merge, like chromatic aberration.
 *
 * Every beam runs past the viewBox edge and is clipped there, so the streams
 * read as continuing to infinity (no end caps, no end dots).
 *
 * Geometry is GENERATED: design/brand/prism-geometry.py (rerun it and paste
 * its output below to change the mark). Colors come from the CSS variables
 * (--color-stream-audio/-video) so the mark can never drift from the theme.
 */
interface PrismLogoProps {
  /** Rendered width in px; height follows the 120:64 viewBox ratio. */
  size?: number;
  /** Audio-only: dim the video (orange) stream to a faint trace. */
  audioOnly?: boolean;
  className?: string;
}

export const PRISM_VIEW_W = 120;
export const PRISM_VIEW_H = 64;

// --- generated by design/brand/prism-geometry.py (defaults) ---
export const PRISM_TRIANGLE = '56.0,8.0 80.5,56.0 31.5,56.0';
export const PRISM_MEET = { x: 56.0, y: 40.0 };
export const PRISM_EXIT_POINT = { x: 70.8, y: 37.1 };
export const PRISM_AUDIO_ENTRY = { x: 41.8, y: 35.8 };
export const PRISM_VIDEO_ENTRY = { x: 39.4, y: 40.6 };
export const PRISM_AUDIO_BEAM = 'M -6.0 26.6 L 41.8 35.8 L 56.0 40.0';
export const PRISM_VIDEO_BEAM = 'M -6.0 57.2 L 39.4 40.6 L 56.0 40.0';
export const PRISM_GLASS_BEAM = 'M 56.0 40.0 L 70.8 37.1';
export const PRISM_EXIT_BEAM = 'M 70.8 37.1 L 126.0 34.2';
/** Unit normal of the exit beam (fringe offsets), y-down. */
export const PRISM_EXIT_NORMAL = { x: -0.0523, y: -0.9986 };
// --- end generated ---

export const PRISM_BEAM_WIDTH = 2.6;
/** The combined stream is the strongest line in the mark. */
export const PRISM_EXIT_WIDTH = 6.4;
export const PRISM_FRINGE_WIDTH = 1.1;
export const PRISM_OUTLINE_WIDTH = 2.2;

/** Audio-only pale state: a faint, desaturated trace of the video stream
 *  (owner 2026-10-19: "even more subdued" than the first 0.35). */
export const PRISM_PALE_OPACITY = 0.18;
export const PRISM_PALE_FILTER = 'saturate(0.25) brightness(1.3)';

const nums = (path: string) => path.replace(/[ML]/g, ' ').trim().split(/\s+/).map(Number);
const toPath = (v: number[]) =>
  'M ' + Array.from({ length: v.length / 2 }, (_, i) => `${v[2 * i].toFixed(2)} ${v[2 * i + 1].toFixed(2)}`).join(' L ');

/** Slide a polyline's first point (or last, `atEnd`) along its own segment
 *  until it reaches x = `toX`: lengthens a beam without changing its angle. */
function reachX(path: string, toX: number, atEnd = false) {
  const v = nums(path);
  const [i, j] = atEnd ? [v.length - 2, v.length - 4] : [0, 2];
  const [x0, y0, x1, y1] = [v[j], v[j + 1], v[i], v[i + 1]];
  v[i] = toX;
  v[i + 1] = y0 + ((y1 - y0) * (toX - x0)) / (x1 - x0);
  return toPath(v);
}

/** Offset a straight 'M x y L x y' path sideways along `n` by `d` units. */
function offsetPath(path: string, n: { x: number; y: number }, d: number) {
  const v = nums(path);
  const p = (i: number) => `${(v[i] + n.x * d).toFixed(2)} ${(v[i + 1] + n.y * d).toFixed(2)}`;
  return `M ${p(0)} L ${p(2)}`;
}

export interface PrismMarkProps {
  /** Stroke multiplier (heavier at small render sizes). */
  k?: number;
  audioOpacity?: number;
  videoOpacity?: number;
  audioFilter?: string;
  videoFilter?: string;
  /** Opacity of the merged white stream (glass segment, exit beam, fringes). */
  combinedOpacity?: number;
  transition?: string;
  /** How far (viewBox units) the beams run past the 120x64 box before being
   *  clipped. Default 0 = clip at the box; the dock icon passes more so the
   *  streams cross the whole icon panel. */
  reach?: number;
}

/**
 * The mark's drawing, shared by PrismLogo and PrismConvergeToggle so both
 * render one geometry. Must sit inside a 120x64 viewBox <svg>.
 */
export function PrismMark({
  k = 1,
  audioOpacity = 1,
  videoOpacity = 1,
  audioFilter,
  videoFilter,
  combinedOpacity = 1,
  transition = 'opacity 300ms ease, filter 300ms ease',
  reach = 0,
}: PrismMarkProps) {
  const audioBeam = reachX(PRISM_AUDIO_BEAM, -reach - 4);
  const videoBeam = reachX(PRISM_VIDEO_BEAM, -reach - 4);
  const exitBeam = reachX(PRISM_EXIT_BEAM, PRISM_VIEW_W + reach + 4, true);
  const uid = useId().replace(/:/g, '');
  const clip = `${uid}-clip`;
  const bw = PRISM_BEAM_WIDTH * k;
  const ew = PRISM_EXIT_WIDTH * k;
  const fw = PRISM_FRINGE_WIDTH * k;
  // Fringes ride the white beam's edges. Order is INVERTED vs entry: teal
  // came in on top, so it leaves on the bottom edge, orange on the top.
  const edge = ew / 2 - fw / 2;
  const n = PRISM_EXIT_NORMAL; // points up-screen
  const merge = [
    { id: `${uid}-ma`, from: PRISM_AUDIO_ENTRY },
    { id: `${uid}-mv`, from: PRISM_VIDEO_ENTRY },
  ];
  return (
    <>
      <defs>
        <clipPath id={clip}>
          <rect x={-reach} y={-reach} width={PRISM_VIEW_W + 2 * reach} height={PRISM_VIEW_H + 2 * reach} />
        </clipPath>
        {merge.map(({ id, from }) => (
          <linearGradient
            key={id}
            id={id}
            gradientUnits="userSpaceOnUse"
            x1={from.x}
            y1={from.y}
            x2={PRISM_MEET.x}
            y2={PRISM_MEET.y}
          >
            <stop offset="0" stopColor="#FFFFFF" stopOpacity="0" />
            <stop offset="1" stopColor="#FFFFFF" stopOpacity="1" />
          </linearGradient>
        ))}
      </defs>

      <polygon
        points={PRISM_TRIANGLE}
        fill="rgba(255,255,255,0.04)"
        stroke="rgba(255,255,255,0.9)"
        strokeWidth={PRISM_OUTLINE_WIDTH * k}
        strokeLinejoin="round"
      />

      <g clipPath={`url(#${clip})`} fill="none" strokeLinejoin="round">
        <path
          data-testid="mark-audio-beam"
          d={audioBeam}
          stroke="var(--color-stream-audio)"
          strokeWidth={bw}
          opacity={audioOpacity}
          style={{ filter: audioFilter, transition }}
        />
        <path
          data-testid="mark-video-beam"
          d={videoBeam}
          stroke="var(--color-stream-video)"
          strokeWidth={bw}
          opacity={videoOpacity}
          style={{ filter: videoFilter, transition }}
        />

        <g data-testid="mark-combined" opacity={combinedOpacity} style={{ transition }}>
          {/* Colours fade to white where the streams merge inside the glass */}
          {merge.map(({ id, from }) => (
            <line
              key={id}
              x1={from.x}
              y1={from.y}
              x2={PRISM_MEET.x}
              y2={PRISM_MEET.y}
              stroke={`url(#${id})`}
              strokeWidth={bw}
            />
          ))}
          {/* Merged beam inside the glass, centroid -> right face */}
          <path d={PRISM_GLASS_BEAM} stroke="#FFFFFF" strokeWidth={bw * 1.4} strokeLinecap="round" />
          {/* The combined stream leaving the prism: thick, slightly rising */}
          <path data-testid="mark-exit-beam" d={exitBeam} stroke="#FFFFFF" strokeWidth={ew} />
          <path
            data-testid="mark-fringe-top"
            d={offsetPath(exitBeam, n, edge)}
            stroke="var(--color-stream-video)"
            strokeWidth={fw}
            opacity={videoOpacity}
            style={{ filter: videoFilter, transition }}
          />
          <path
            data-testid="mark-fringe-bottom"
            d={offsetPath(exitBeam, n, -edge)}
            stroke="var(--color-stream-audio)"
            strokeWidth={fw}
            opacity={audioOpacity}
            style={{ filter: audioFilter, transition }}
          />
        </g>
      </g>
    </>
  );
}

export function PrismLogo({ size = 24, audioOnly = false, className = '' }: PrismLogoProps) {
  const height = Math.round((size * PRISM_VIEW_H) / PRISM_VIEW_W);
  return (
    <svg
      width={size}
      height={height}
      viewBox={`0 0 ${PRISM_VIEW_W} ${PRISM_VIEW_H}`}
      fill="none"
      className={className}
      aria-hidden="true"
    >
      <PrismMark
        // Small renders (header/sidebar) get heavier strokes so the beams
        // survive at ~26px wide.
        k={size < 40 ? 1.3 : 1}
        videoOpacity={audioOnly ? PRISM_PALE_OPACITY : 1}
        videoFilter={audioOnly ? PRISM_PALE_FILTER : undefined}
      />
    </svg>
  );
}
