import { useId } from 'react';

/**
 * PrismLogo — the EchoPrism brand mark (v4, owner spec 2026-10-19 17:28).
 *
 * A reverse prism traced with Snell's law (n = 1.5). Video (orange) enters
 * from ABOVE and audio (teal) from below, matching an editing timeline (video
 * track over audio track). Each bends toward the face normal on entry, and
 * they cross at the triangle's centroid, the focus.
 *
 * Past the focus the merged light spreads as a wedge to the right face and
 * leaves as one thick band. The colours went straight through the focus, so
 * they come out INVERTED (teal on top, orange below), as fringes on the
 * band's edges: an imperfect merge, like chromatic aberration. The fringes
 * are part of the wedge, so they start AT the focus, not at the exit face.
 *
 * Anti-aliasing: the band (wedge + exit) is ONE filled shape coloured by a
 * gradient ACROSS its width (teal edge, white core, orange edge), never thin
 * strokes. A gradient is evaluated per pixel, so its colour bands have no
 * stair steps at any angle, and the band's only edges are its thick outer
 * outline. A 1px stroke at a shallow angle, by contrast, steps every few
 * dozen pixels, and the step is the whole stroke.
 *
 * Beams run past the viewBox and are clipped there, so they read as
 * continuing to infinity. Geometry is GENERATED by
 * design/brand/prism-geometry.py; colours come from the theme variables.
 */
interface PrismLogoProps {
  /** Rendered width in px; height follows the 120:64 viewBox ratio. */
  size?: number;
  /** Audio-only: dim the video (orange) stream to a faint trace. */
  audioOnly?: boolean;
  className?: string;
}

type Pt = { x: number; y: number };
export interface PrismGeometry {
  triangle: string;
  /** The focus: where the streams cross (the triangle's centroid). */
  meet: Pt;
  video: { entry: Pt; beam: string };
  audio: { entry: Pt; beam: string };
  /** Exit band edges on the right face, and the band's direction. */
  exitTop: Pt;
  exitBottom: Pt;
  exitDir: Pt;
}

export const PRISM_VIEW_W = 120;
export const PRISM_VIEW_H = 64;

// generated by design/brand/prism-geometry.py --apex 56 --h 48 --n 1.5 --exit-deg 0 --uv 0.56 --ua 0.68 --band 7
export const PRISM_GEOMETRY: PrismGeometry = {
  triangle: '56.00,8.00 81.52,56.00 30.48,56.00',
  meet: {
    x: 56.0,
    y: 40.0
  },
  video: {
    entry: {
      x: 41.71,
      y: 34.88
    },
    beam: 'M -6.00 21.64 L 41.71 34.88 L 56.00 40.00'
  },
  audio: {
    entry: {
      x: 38.65,
      y: 40.64
    },
    beam: 'M -6.00 57.61 L 38.65 40.64 L 56.00 40.00'
  },
  exitTop: {
    x: 69.73,
    y: 33.82
  },
  exitBottom: {
    x: 73.45,
    y: 40.82
  },
  exitDir: {
    x: 1.0,
    y: -0.0
  }
};

export const PRISM_MEET = PRISM_GEOMETRY.meet;

export const PRISM_BEAM_WIDTH = 2.6;
export const PRISM_OUTLINE_WIDTH = 2.2;
/** Share of the band's width given to each colour fringe. */
export const PRISM_FRINGE_SHARE = 0.2;

/** Audio-only pale state: a faint, desaturated trace of the video stream. */
export const PRISM_PALE_OPACITY = 0.18;
export const PRISM_PALE_FILTER = 'saturate(0.25) brightness(1.3)';

const nums = (path: string) => path.replace(/[ML]/g, ' ').trim().split(/\s+/).map(Number);
const toPath = (v: number[]) =>
  'M ' + Array.from({ length: v.length / 2 }, (_, i) => `${v[2 * i].toFixed(2)} ${v[2 * i + 1].toFixed(2)}`).join(' L ');

/** Slide a polyline's first point along its own segment to x = `toX`:
 *  lengthens a beam without changing its angle. */
function reachX(path: string, toX: number) {
  const v = nums(path);
  const [x0, y0, x1, y1] = [v[2], v[3], v[0], v[1]];
  v[0] = toX;
  v[1] = y0 + ((y1 - y0) * (toX - x0)) / (x1 - x0);
  return toPath(v);
}

export interface PrismMarkProps {
  /** Stroke multiplier (heavier at small render sizes). */
  k?: number;
  audioOpacity?: number;
  videoOpacity?: number;
  audioFilter?: string;
  videoFilter?: string;
  /** Opacity of the merged band (white core and both fringes). */
  combinedOpacity?: number;
  transition?: string;
  /** How far (viewBox units) the beams run past the 120x64 box before being
   *  clipped. Callers inside a framed badge pass enough to reach the frame. */
  reach?: number;
  /** Override the generated geometry (preview harnesses only). */
  geometry?: PrismGeometry;
}

/**
 * The mark's drawing, shared by PrismLogo, PrismConvergeToggle and the dock
 * icon build, so all render one geometry. Must sit inside a 120x64 viewBox.
 */
export function PrismMark({
  k = 1,
  audioOpacity = 1,
  videoOpacity = 1,
  audioFilter,
  videoFilter,
  combinedOpacity = 1,
  transition = 'opacity 300ms ease, filter 300ms ease',
  reach = 0,
  geometry: g = PRISM_GEOMETRY,
}: PrismMarkProps) {
  // useId is unique within one React root; separate static renders (the dock
  // icon build, preview pages) each start from the same ids, so a geometry
  // key is mixed in to keep their gradients from resolving to each other.
  const key = Math.round((g.exitTop.y + g.exitDir.y * 100) * 100).toString(36);
  const uid = `${useId().replace(/:/g, '')}-${key}`;
  const far = reach + 4;
  const videoBeam = reachX(g.video.beam, -far);
  const audioBeam = reachX(g.audio.beam, -far);

  // The exit band: a parallel strip from the right face out to the far edge.
  const run = PRISM_VIEW_W + far - Math.min(g.exitTop.x, g.exitBottom.x);
  const out = (p: Pt) => ({ x: p.x + g.exitDir.x * run * 2, y: p.y + g.exitDir.y * run * 2 });
  const [T2, B2] = [out(g.exitTop), out(g.exitBottom)];
  const band = `M ${g.exitTop.x} ${g.exitTop.y} L ${T2.x} ${T2.y} L ${B2.x} ${B2.y} L ${g.exitBottom.x} ${g.exitBottom.y} Z`;

  // Cross-band gradient axis: perpendicular to the exit direction, spanning
  // the band from its top edge to its bottom edge.
  const nx = -g.exitDir.y;
  const ny = g.exitDir.x;
  const w = (g.exitBottom.x - g.exitTop.x) * nx + (g.exitBottom.y - g.exitTop.y) * ny;
  const gx1 = g.exitTop.x;
  const gy1 = g.exitTop.y;
  const gx2 = g.exitTop.x + nx * w;
  const gy2 = g.exitTop.y + ny * w;
  // Small renders give the fringes a larger share of the band so each
  // colour ramp stays over ~1 device px wide.
  const f = Math.min(0.3, PRISM_FRINGE_SHARE * k);

  // The wedge inside the glass: focus -> right face. White, with each colour
  // as a thin sliver that starts AT the focus and widens to meet its fringe
  // on the band (sliver edge = the fringe ramp's midpoint, 0.85 f). A linear
  // gradient cannot follow a narrowing shape, so the wedge is filled shapes.
  const along = (t: number) => ({
    x: g.exitTop.x + (g.exitBottom.x - g.exitTop.x) * t,
    y: g.exitTop.y + (g.exitBottom.y - g.exitTop.y) * t,
  });
  const [st, sb] = [along(f * 0.85), along(1 - f * 0.85)];
  const tri = (a: Pt, b: Pt) => `M ${g.meet.x} ${g.meet.y} L ${a.x} ${a.y} L ${b.x} ${b.y} Z`;
  const wedge = tri(g.exitTop, g.exitBottom);

  const ids = { clip: `${uid}-clip`, band: `${uid}-band`, va: `${uid}-va`, aa: `${uid}-aa` };
  return (
    <>
      <defs>
        <clipPath id={ids.clip}>
          <rect x={-reach} y={-reach} width={PRISM_VIEW_W + 2 * reach} height={PRISM_VIEW_H + 2 * reach} />
        </clipPath>
        {/* Inverted fringes (teal top, orange bottom) around a white core.
            Every colour change is a soft RAMP, never a hard stop: browsers
            antialias shape edges by coverage but sample a gradient once per
            pixel centre, so a hard stop is a step that beads on a rising
            band. A ramp at least ~1 device px wide leaves nothing to alias. */}
        <linearGradient id={ids.band} gradientUnits="userSpaceOnUse" x1={gx1} y1={gy1} x2={gx2} y2={gy2}>
          <stop offset="0" stopColor="var(--color-stream-audio)" stopOpacity={audioOpacity} />
          <stop offset={f * 0.35} stopColor="var(--color-stream-audio)" stopOpacity={audioOpacity} />
          <stop offset={f * 1.35} stopColor="#FFFFFF" />
          <stop offset={1 - f * 1.35} stopColor="#FFFFFF" />
          <stop offset={1 - f * 0.35} stopColor="var(--color-stream-video)" stopOpacity={videoOpacity} />
          <stop offset="1" stopColor="var(--color-stream-video)" stopOpacity={videoOpacity} />
        </linearGradient>
        {/* Each incoming stream fades to white as it nears the focus */}
        {[
          { id: ids.va, from: g.video.entry },
          { id: ids.aa, from: g.audio.entry },
        ].map(({ id, from }) => (
          <linearGradient key={id} id={id} gradientUnits="userSpaceOnUse" x1={from.x} y1={from.y} x2={g.meet.x} y2={g.meet.y}>
            <stop offset="0" stopColor="#FFFFFF" stopOpacity="0" />
            <stop offset="1" stopColor="#FFFFFF" stopOpacity="1" />
          </linearGradient>
        ))}
      </defs>

      <polygon
        points={g.triangle}
        fill="rgba(255,255,255,0.04)"
        stroke="rgba(255,255,255,0.9)"
        strokeWidth={PRISM_OUTLINE_WIDTH * k}
        strokeLinejoin="round"
      />

      <g clipPath={`url(#${ids.clip})`} fill="none" strokeLinejoin="round">
        <path
          data-testid="mark-video-beam"
          d={videoBeam}
          stroke="var(--color-stream-video)"
          strokeWidth={PRISM_BEAM_WIDTH * k}
          opacity={videoOpacity}
          style={{ filter: videoFilter, transition }}
        />
        <path
          data-testid="mark-audio-beam"
          d={audioBeam}
          stroke="var(--color-stream-audio)"
          strokeWidth={PRISM_BEAM_WIDTH * k}
          opacity={audioOpacity}
          style={{ filter: audioFilter, transition }}
        />

        <g data-testid="mark-combined" opacity={combinedOpacity} style={{ transition }}>
          {[
            { id: ids.va, from: g.video.entry },
            { id: ids.aa, from: g.audio.entry },
          ].map(({ id, from }) => (
            <line key={id} x1={from.x} y1={from.y} x2={g.meet.x} y2={g.meet.y} stroke={`url(#${id})`} strokeWidth={PRISM_BEAM_WIDTH * k} />
          ))}
          {/* Wedge: white light spreading from the focus to the right face,
              with the colour slivers (inverted order) converging on the focus */}
          <path data-testid="mark-exit-wedge" d={wedge} fill="#FFFFFF" />
          <path d={tri(g.exitTop, st)} fill="var(--color-stream-audio)" fillOpacity={audioOpacity} style={{ filter: audioFilter }} />
          <path d={tri(sb, g.exitBottom)} fill="var(--color-stream-video)" fillOpacity={videoOpacity} style={{ filter: videoFilter }} />
          {/* The band leaving the prism: one filled shape, fringes in its gradient */}
          <path data-testid="mark-exit-band" d={band} fill={`url(#${ids.band})`} stroke="none" />
        </g>
      </g>
    </>
  );
}

export function PrismLogo({ size = 24, audioOnly = false, className = '' }: PrismLogoProps) {
  const height = Math.round((size * PRISM_VIEW_H) / PRISM_VIEW_W);
  return (
    <svg
      width={size}
      height={height}
      viewBox={`0 0 ${PRISM_VIEW_W} ${PRISM_VIEW_H}`}
      fill="none"
      className={className}
      aria-hidden="true"
    >
      <PrismMark
        // Small renders (header/sidebar) get heavier strokes so the beams
        // survive at ~26px wide.
        k={size < 40 ? 1.3 : 1}
        videoOpacity={audioOnly ? PRISM_PALE_OPACITY : 1}
        videoFilter={audioOnly ? PRISM_PALE_FILTER : undefined}
      />
    </svg>
  );
}
