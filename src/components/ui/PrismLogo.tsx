export const PRISM_MEET = PRISM_GEOMETRY.meet;

/** Incoming beam width (viewBox units). */
export const PRISM_BEAM_WIDTH = 3.6;
/** The prism outline is deliberately dimmer than the light it bends. */
export const PRISM_OUTLINE_WIDTH = 1.8;
export const PRISM_OUTLINE_COLOR = 'rgba(255,255,255,0.45)';
/** At badge sizes (~26px) the outline is only just over half a pixel wide;
 *  a little more alpha keeps it legible there. */
export const PRISM_OUTLINE_COLOR_SMALL = 'rgba(255,255,255,0.55)';
/** Share of the band's width given to each colour fringe at large sizes. */
export const PRISM_FRINGE_SHARE = 0.16;
/** Minimum fringe width in device px (assumes a 2x display), so a fringe
 *  never drops below a pixel and beads. */
export const PRISM_FRINGE_MIN_DEVICE_PX = 3;

/** Audio-only pale state: a faint, desaturated trace of the video stream. */
export const PRISM_PALE_OPACITY = 0.18;
export const PRISM_PALE_FILTER = 'saturate(0.25) brightness(1.3)';

const add = (p: Pt, q: Pt, t = 1): Pt => ({ x: p.x + q.x * t, y: p.y + q.y * t });
const unit = (p: Pt, q: Pt): Pt => {
  const l = Math.hypot(q.x - p.x, q.y - p.y);
  return { x: (q.x - p.x) / l, y: (q.y - p.y) / l };
};
const poly = (...pts: Pt[]) => 'M ' + pts.map((p) => `${p.x.toFixed(3)} ${p.y.toFixed(3)}`).join(' L ') + ' Z';
const parse = (path: string): Pt[] => {
  const v = path.replace(/[MLZ]/g, ' ').trim().split(/\s+/).map(Number);
  return Array.from({ length: v.length / 2 }, (_, i) => ({ x: v[2 * i], y: v[2 * i + 1] }));
};
/** Intersection of lines p + s*d and q + t*e. */
const meetLines = (p: Pt, d: Pt, q: Pt, e: Pt): Pt => {
  const den = d.x * e.y - d.y * e.x;
  const s = ((q.x - p.x) * e.y - (q.y - p.y) * e.x) / den;
  return add(p, d, s);
};

/**
 * One incoming stream as a filled shape: constant width outside the glass,
 * a mitred bend at the entry face, then a straight taper to a sharp point at
 * the focus. Returns the outline and the inside-the-glass triangle (for the
 * fade to white).
 */
function taperedBeam(beam: string, width: number, farX: number) {
  const [, P, F] = parse(beam); // [outside start, entry, focus]
  const d2 = unit(P, F);
  const S0 = parse(beam)[0];
  const d1 = unit(S0, P);
  const far = add(P, d1, (farX - P.x) / d1.x);
  const hw = width / 2;
  const n1 = { x: -d1.y, y: d1.x };
  const n2 = { x: -d2.y, y: d2.x };
  const side = (sgn: number) => meetLines(add(far, n1, sgn * hw), d1, add(P, n2, sgn * hw), d2);
  const [mA, mB] = [side(1), side(-1)];
  return {
    outline: poly(add(far, n1, hw), mA, F, mB, add(far, n1, -hw)),
    inside: poly(mA, F, mB),
    entry: P,
  };
}

export interface PrismMarkProps {
  /** Stroke multiplier (heavier at small render sizes). */
  k?: number;
  audioOpacity?: number;
  videoOpacity?: number;
  audioFilter?: string;
  videoFilter?: string;
  /** Opacity of the merged band (white core and both fringes). */
  combinedOpacity?: number;
  transition?: string;
  /** How far (viewBox units) the beams run past the 120x64 box before being
   *  clipped. Callers inside a framed badge pass enough to reach the frame. */
  reach?: number;
  /** Override the generated geometry (preview harnesses only). */
  geometry?: PrismGeometry;
  /** Rendered width of the 120-unit box in CSS px: sizes the fringes so they
   *  never drop below a device pixel. */
  pxWidth?: number;
}

/**
 * The mark's drawing, shared by PrismLogo, PrismConvergeToggle and the dock
 * icon build, so all render one geometry. Must sit inside a 120x64 viewBox.
 */
export function PrismMark({
  k = 1,
  audioOpacity = 1,
  videoOpacity = 1,
  audioFilter,
  videoFilter,
  combinedOpacity = 1,
  transition = 'opacity 300ms ease, filter 300ms ease',
  reach = 0,
  geometry: g = PRISM_GEOMETRY,
  pxWidth = 120,
}: PrismMarkProps) {
  // useId is unique within one React root; separate static renders (the dock
  // icon build, preview pages) each start from the same ids, so a geometry
  // key is mixed in to keep their gradients from resolving to each other.
  const key = Math.round((g.exitTop.y + g.exitDir.y * 100) * 100).toString(36);
  const uid = `${useId().replace(/:/g, '')}-${key}`;
  const farX = -(reach + 4);
  const video = taperedBeam(g.video.beam, PRISM_BEAM_WIDTH * k, farX);
  const audio = taperedBeam(g.audio.beam, PRISM_BEAM_WIDTH * k, farX);

  // Exit: wedge (focus -> right face) + band (face -> far edge), as ONE
  // white shape with the two fringe slivers laid over it. Fringe width is a
  // fixed fraction of the band's width, so in the wedge each sliver narrows
  // in proportion and converges exactly on the focus: same look inside and
  // outside the glass, no seam at the exit face.
  const run = (PRISM_VIEW_W + reach + 4 - Math.min(g.exitTop.x, g.exitBottom.x)) * 2;
  const T = g.exitTop;
  const B = g.exitBottom;
  const far = (p: Pt) => add(p, g.exitDir, run);
  // Band width perpendicular to its direction (|exitDir x (B - T)|).
  const bandW = Math.abs(g.exitDir.x * (B.y - T.y) - g.exitDir.y * (B.x - T.x));
  const unitsPerDevicePx = PRISM_VIEW_W / (pxWidth * 2);
  const fringe = Math.min(0.3 * bandW, Math.max(PRISM_FRINGE_SHARE * bandW, PRISM_FRINGE_MIN_DEVICE_PX * unitsPerDevicePx));
  const f = fringe / bandW;
  const along = (t: number) => ({ x: T.x + (B.x - T.x) * t, y: T.y + (B.y - T.y) * t });
  const [a, b] = [along(f), along(1 - f)];
  const M = g.meet;
  const white = poly(M, T, far(T), far(B), B);
  const fringeTop = poly(M, T, far(T), far(a), a);
  const fringeBottom = poly(M, b, far(b), far(B), B);

  const ids = { clip: `${uid}-clip`, va: `${uid}-va`, aa: `${uid}-aa` };
  return (
    <>
      <defs>
        <clipPath id={ids.clip}>
          <rect x={-reach} y={-reach} width={PRISM_VIEW_W + 2 * reach} height={PRISM_VIEW_H + 2 * reach} />
        </clipPath>
        {/* Each incoming stream fades to white as it nears the focus */}
        {[
          { id: ids.va, from: video.entry },
          { id: ids.aa, from: audio.entry },
        ].map(({ id, from }) => (
          <linearGradient key={id} id={id} gradientUnits="userSpaceOnUse" x1={from.x} y1={from.y} x2={g.meet.x} y2={g.meet.y}>
            <stop offset="0" stopColor="#FFFFFF" stopOpacity="0" />
            <stop offset="1" stopColor="#FFFFFF" stopOpacity="1" />
          </linearGradient>
        ))}
      </defs>

      <polygon
        points={g.triangle}
        fill="rgba(255,255,255,0.03)"
        stroke={pxWidth < 40 ? PRISM_OUTLINE_COLOR_SMALL : PRISM_OUTLINE_COLOR}
        // Floor at 0.7 CSS px: thinner, antialiasing dims the hairline below
        // its colour no matter how bright it is (badge marks are ~24px wide).
        strokeWidth={Math.max(PRISM_OUTLINE_WIDTH * k, (0.7 * PRISM_VIEW_W) / pxWidth)}
        strokeLinejoin="round"
      />

      <g clipPath={`url(#${ids.clip})`} stroke="none">
        <path
          data-testid="mark-video-beam"
          d={video.outline}
          fill="var(--color-stream-video)"
          opacity={videoOpacity}
          style={{ filter: videoFilter, transition }}
        />
        <path
          data-testid="mark-audio-beam"
          d={audio.outline}
          fill="var(--color-stream-audio)"
          opacity={audioOpacity}
          style={{ filter: audioFilter, transition }}
        />

        <g data-testid="mark-combined" opacity={combinedOpacity} style={{ transition }}>
          {/* Inside the glass each stream whitens as it tapers into the focus */}
          <path d={video.inside} fill={`url(#${ids.va})`} />
          <path d={audio.inside} fill={`url(#${ids.aa})`} />
          {/* Merged light: wedge from the focus + the band beyond the face */}
          <path data-testid="mark-exit-band" d={white} fill="#FFFFFF" />
          {/* Inverted fringes, each one sliver from the focus to infinity */}
          <path
            data-testid="mark-fringe-top"
            d={fringeTop}
            fill="var(--color-stream-audio)"
            opacity={audioOpacity}
            style={{ filter: audioFilter, transition }}
          />
          <path
            data-testid="mark-fringe-bottom"
            d={fringeBottom}
            fill="var(--color-stream-video)"
            opacity={videoOpacity}
            style={{ filter: videoFilter, transition }}
          />
        </g>
      </g>
    </>
  );
}

export function PrismLogo({ size = 24, audioOnly = false, className = '' }: PrismLogoProps) {
  const height = Math.round((size * PRISM_VIEW_H) / PRISM_VIEW_W);
  return (
    <svg
      width={size}
      height={height}
      viewBox={`0 0 ${PRISM_VIEW_W} ${PRISM_VIEW_H}`}
      fill="none"
      className={className}
      aria-hidden="true"
    >
      <PrismMark
        // Small renders (header/sidebar) get heavier strokes so the beams
        // survive at ~26px wide.
        k={size < 40 ? 1.3 : 1}
        pxWidth={size}
        videoOpacity={audioOnly ? PRISM_PALE_OPACITY : 1}
        videoFilter={audioOnly ? PRISM_PALE_FILTER : undefined}
      />
    </svg>
  );
}
