import { useId } from 'react';

/**
 * PrismLogo — the EchoPrism brand mark (v5, owner spec 2026-10-19 18:05).
 *
 * A reverse prism traced with Snell's law (n = 1.5). Video (orange) enters
 * from ABOVE and audio (teal) from below, matching an editing timeline. Each
 * bends toward the face normal on entry and TAPERS to a sharp point at the
 * triangle's centroid, the focus. From that same point the merged light
 * spreads as a wedge to the right face and leaves as one thick band rising
 * at +6 degrees (a falling line reads as decline).
 *
 * The colours went straight through the focus, so they come out INVERTED
 * (teal on top, orange below) as fringes: an imperfect merge, like chromatic
 * aberration. Each fringe is ONE filled sliver from the focus, through the
 * wedge, out along the band, so it is identical inside and outside the glass.
 *
 * Every part is a filled shape, never a thin stroke: shape edges antialias by
 * pixel coverage, and each fringe is kept at least ~1.5 device px wide at the
 * size it renders (`pxWidth`), so its edges stay sharp without beading.
 * (A sub-pixel stroke cannot be both sharp and step-free; a gradient ramp
 * avoids steps but blurs, which reads too soft for chromatic aberration.)
 *
 * Beams run past the viewBox and are clipped there, so they read as
 * continuing to infinity. Geometry is GENERATED by
 * design/brand/prism-geometry.py; colours come from the theme variables.
 */
interface PrismLogoProps {
  /** Rendered width in px; height follows the 120:64 viewBox ratio. */
  size?: number;
  /** Audio-only: dim the video (orange) stream to a faint trace. */
  audioOnly?: boolean;
  className?: string;
}

type Pt = { x: number; y: number };
export interface PrismGeometry {
  triangle: string;
  /** The focus: where the streams cross (the triangle's centroid). */
  meet: Pt;
  video: { entry: Pt; beam: string };
  audio: { entry: Pt; beam: string };
  /** Exit band edges on the right face, and the band's direction. */
  exitTop: Pt;
  exitBottom: Pt;
  exitDir: Pt;
}

export const PRISM_VIEW_W = 120;
export const PRISM_VIEW_H = 64;

